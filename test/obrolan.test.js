import test from 'node:test';
import assert from 'node:assert/strict';
process.env.POKOMEN_MEMORY_DB = '1';
const { newWarga } = await import('../lib/rules.js');
const { setJSON, redis } = await import('../lib/db.js');
const ob = await import('../lib/obrolan.js');
await redis('SET', 'tier_schema', '6');
test('filter pesan', () => {
  assert.equal(ob.cekPesan('halo semua, selamat Ketua Hole!'), null);
  assert.match(ob.cekPesan('cek www.situs.com'), /Link/);
  assert.match(ob.cekPesan('wa aku 0812 3456 7890'), /Nomor HP|pindah/);
  assert.match(ob.cekPesan('dasar g0bl0k'), /tidak sopan/);
  assert.match(ob.cekPesan('a'.repeat(201)), /200/);
  assert.match(ob.cekPesan('chat wa aja yuk'), /pindah/);
  assert.match(ob.cekPesan('halo @temanku'), /nama hewan/);
});
test('tulis & baca obrolan', async () => {
  await setJSON('warga', 'val', newWarga({ username: 'val', nama: 'Valtherion', hewan: ['Naga'], spot: 1 }));
  await setJSON('warga', 'hole', newWarga({ username: 'hole', nama: 'Hole', hewan: ['Naga'], spot: 71 }));
  const k = await ob.tokenFor('val');
  assert.equal(await ob.userFromToken(k), 'val');
  assert.ok((await ob.tulis({ token: 'salah', ruang: 'semua', text: 'hai' })).error);
  const r = await ob.tulis({ token: k, ruang: 'semua', text: 'Halo semua!' });
  assert.equal(r.pesan.nama, 'Valtherion'); assert.equal(r.pesan.wil, 1);
  assert.match((await ob.tulis({ token: k, ruang: 'w2', text: 'hai wilayah 2' })).error, /hanya bisa membaca/);
  await redis('DEL', 'ob_rl:val');
  assert.match((await ob.tulis({ token: k, ruang: 'semua', text: 'halo semua!' })).error, /sama/);
  await redis('DEL', 'ob_rl:val');
  assert.ok((await ob.tulis({ token: k, ruang: 'w1', text: 'Wilayah 1 kompak!' })).ok);
  assert.equal((await ob.baca('semua')).length, 1);
  await ob.adminBisukan('val', 60); await redis('DEL', 'ob_rl:val');
  assert.match((await ob.tulis({ token: k, ruang: 'semua', text: 'tes lagi' })).error, /dibisukan/);
  await ob.adminBisukan('val', 0);
  const k2 = await ob.tokenFor('val', { baru: true });
  assert.equal(await ob.userFromToken(k), null); assert.equal(await ob.userFromToken(k2), 'val');
  const id = (await ob.baca('semua'))[0].id;
  const kh = await ob.tokenFor('hole');
  await ob.lapor({ token: kh, id }); await ob.lapor({ token: k2, id });
  assert.equal((await ob.baca('semua')).length, 1);
  await setJSON('warga', 'x3', newWarga({ username: 'x3', nama: 'X', hewan: ['Kucing'], spot: 5 }));
  assert.equal((await ob.lapor({ token: await ob.tokenFor('x3'), id })).disembunyikan, true);
  assert.equal((await ob.baca('semua')).length, 0);
});
